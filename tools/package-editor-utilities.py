"""Generate offline UI data from the pinned Unicode/font/license resources."""
from pathlib import Path
import bisect
import json
import re
import struct
import sys
import tomllib

root = Path(__file__).resolve().parents[1]
assert sys.argv[1:] in ([], ['--check']), 'Usage: py tools/package-editor-utilities.py [--check]'

def write_asset(name, content):
    path = root / name
    if sys.argv[1:]:
        if not path.is_file() or path.read_bytes() != content.encode('utf-8'):
            raise SystemExit(f'Generated UI asset is stale: {name}')
    else:
        path.write_text(content, encoding='utf-8', newline='\n')
ucd = root / 'data/ucd/17.0.0'
font = (root / 'data/fonts/carlito/Carlito-Regular.ttf').read_bytes()
u16 = lambda at: struct.unpack_from('>H', font, at)[0]
u32 = lambda at: struct.unpack_from('>I', font, at)[0]
tables = {font[at:at+4]: u32(at+8) for at in range(12, 12 + 16*u16(4), 16)}
cmap = tables[b'cmap']
coverage = set()
for i in range(u16(cmap+2)):
    record = cmap+4+8*i
    platform, encoding, sub = u16(record), u16(record+2), cmap+u32(record+4)
    if platform != 0 and (platform != 3 or encoding not in (1, 10)):
        continue
    if u16(sub) == 12:
        for j in range(u32(sub+12)):
            start, end, glyph = struct.unpack_from('>III', font, sub+16+12*j)
            assert start <= end <= 0x10ffff
            coverage.update(c for c in range(start, end+1) if glyph+c-start)
    elif u16(sub) == 4:
        count = u16(sub+6)//2
        ends = sub+14
        starts = ends+2*count+2
        deltas = starts+2*count
        offsets = deltas+2*count
        for j in range(count):
            delta, offset = u16(deltas+2*j), u16(offsets+2*j)
            start, end = u16(starts+2*j), u16(ends+2*j)
            for c in range(start, min(end+1, 0xffff)):
                gid = u16(offsets+2*j+offset+2*(c-start)) if offset else c
                if gid and (gid+delta)&0xffff:
                    coverage.add(c)
blocks=[]
for line in (ucd/'Blocks.txt').read_text(encoding='utf-8').splitlines():
    match=re.match(r'^([0-9A-F]+)\.\.([0-9A-F]+); (.+)',line)
    if match:
        start,end,name=match.groups()
        blocks.append({'id':re.sub(r'[^a-z0-9]+','-',name.lower()).strip('-'),'name':name,'start':int(start,16),'end':int(end,16)})
starts=[b['start'] for b in blocks]
symbols=[]
for line in (ucd/'UnicodeData.txt').read_text(encoding='utf-8').splitlines():
    fields=line.split(';');code=int(fields[0],16)
    if code not in coverage or fields[1].startswith('<') or fields[2].startswith('C') or fields[2] in ('Zl','Zp'):
        continue
    block=blocks[bisect.bisect_right(starts,code)-1]
    assert block['start'] <= code <= block['end']
    symbols.append({'codePoint':code,'name':fields[1],'block':block['id']})
used={s['block'] for s in symbols}
catalogue={'font':'Carlito','unicodeVersion':'17.0.0','blocks':[b for b in blocks if b['id'] in used],'symbols':symbols}
header='// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by tools/package-editor-utilities.py; do not edit.\n'
write_asset('web/symbol-catalogue.mjs', header+'// i18n-ignore: canonical Unicode names and block identifiers from pinned UCD, searched verbatim rather than translated interface messages\nexport const SYMBOL_CATALOGUE = '+json.dumps(catalogue,ensure_ascii=True,separators=(',',':'))+';\n')
licenses={'agpl':(root/'LICENSE').read_text(encoding='utf-8'),'fonts':[{'name':name,'text':(root/f'data/fonts/licenses/{name}-OFL.txt').read_text(encoding='utf-8')} for name in ('Carlito','Caladea','Liberation')],'unicode':(ucd/'LICENSE.txt').read_text(encoding='utf-8')}
write_asset('web/about-licenses.mjs', header+'// i18n-ignore: complete original legal notices must remain verbatim; surrounding interface labels are localized\nexport const ABOUT_LICENSES = '+json.dumps(licenses,ensure_ascii=True,separators=(',',':'))+';\n')
version=tomllib.loads((root/'Cargo.toml').read_text(encoding='utf-8'))['workspace']['package']['version']
fallback={'version':version,'buildDate':None,'sourceUrl':'https://github.com/simkamil/mon-bureau'}
write_asset('web/build-info.mjs', header+'// Development server fallback; the executable serves its compile-time metadata here.\nexport const BUILD_INFO = '+json.dumps(fallback,separators=(',',':'))+';\n')
print(json.dumps({'symbols':len(symbols),'blocks':len(catalogue['blocks']),'fonts':len(licenses['fonts']),'version':version}))
