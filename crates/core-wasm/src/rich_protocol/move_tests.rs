//! Frozen vectors and refusals of `MoveText` (R7c, text drag and drop) and of
//! error 50. Vectors: `tests/rich-editor-move-vectors.txt`, verified here and
//! by `tests/rich-editor-move.mjs` (`ATELIER_REGEN_VECTORS=1` rewrites them).

use super::*;
use std::fmt::Write as _;

const VECTORS: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../tests/rich-editor-move-vectors.txt"
);

fn hex(bytes: &[u8]) -> String {
    bytes.iter().fold(String::new(), |mut s, b| {
        let _ = write!(s, "{b:02x}");
        s
    })
}

fn req(request_id: u32, command: Command) -> Request {
    Request {
        doc_id: 7,
        request_id,
        command,
    }
}

fn describe_request(r: &Request) -> String {
    let head = format!("doc={} req={}", r.doc_id, r.request_id);
    let tail = match &r.command {
        Command::MoveText {
            start,
            end,
            target,
            copy,
        } => format!(
            "MoveText start={start} end={end} target={target} copy={}",
            u8::from(*copy)
        ),
        other => panic!("not a MoveText: {other:?}"),
    };
    format!("{head} {tail}")
}

fn requests() -> Vec<(&'static str, Request)> {
    let mv = |start, end, target, copy| Command::MoveText {
        start,
        end,
        target,
        copy,
    };
    vec![
        ("move", req(1, mv(2, 9, 30, false))),
        ("copy", req(2, mv(0, 1, 0, true))),
        ("move-max", req(3, mv(0, u64::MAX, u64::MAX, false))),
    ]
}

fn frame(body: &[u8]) -> Vec<u8> {
    header(opcode::MOVE_TEXT, 7, 1, body).unwrap()
}

fn body(start: u64, end: u64, target: u64, tail: [u8; 4]) -> Vec<u8> {
    let mut b = start.to_le_bytes().to_vec();
    b.extend_from_slice(&end.to_le_bytes());
    b.extend_from_slice(&target.to_le_bytes());
    b.extend_from_slice(&tail);
    b
}

fn bad_requests() -> Vec<(&'static str, Vec<u8>, ErrorCode)> {
    use ErrorCode::*;
    vec![
        (
            "start-after-end",
            frame(&body(5, 4, 0, [0; 4])),
            InvalidRange,
        ),
        ("copy-2", frame(&body(0, 1, 0, [2, 0, 0, 0])), InvalidBody),
        ("reserved", frame(&body(0, 1, 0, [0, 1, 0, 0])), InvalidBody),
        ("truncated", frame(&[0; 27]), InvalidBody),
        ("trailing", frame(&[0; 29]), InvalidBody),
    ]
}

fn render_vectors() -> String {
    let mut out = String::from(
        "# Frozen ATED v2 vectors of R7c (MoveText, error 50). Columns: kind, name, frame hex, expectation.\n\
         # Generated by the Rust tests of rich_protocol/move_tests.rs (ATELIER_REGEN_VECTORS=1), verified by Rust and tests/rich-editor-move.mjs.\n",
    );
    for (name, r) in requests() {
        let _ = writeln!(
            out,
            "request\t{name}\t{}\t{}",
            hex(&encode_request(&r).unwrap()),
            describe_request(&r)
        );
    }
    let error = encode_reply(&Reply {
        doc_id: 7,
        request_id: 4,
        response: Response::Error(ErrorCode::MoveUnsupported),
    })
    .unwrap();
    let _ = writeln!(
        out,
        "reply\tmove-unsupported-error\t{}\tdoc=7 req=4 Error code=RICH_MOVE_UNSUPPORTED",
        hex(&error)
    );
    for (name, f, code) in bad_requests() {
        let _ = writeln!(out, "bad-request\t{name}\t{}\t{}", hex(&f), code.name());
    }
    out
}

#[test]
fn frozen_vectors_match_encoder() {
    let rendered = render_vectors();
    if std::env::var_os("ATELIER_REGEN_VECTORS").is_some() {
        std::fs::write(VECTORS, &rendered).unwrap();
    }
    let frozen = std::fs::read_to_string(VECTORS)
        .unwrap()
        .replace("\r\n", "\n");
    assert_eq!(frozen, rendered, "vectors are frozen");
}

#[test]
fn valid_frames_round_trip_and_invalid_ones_have_stable_codes() {
    for (name, r) in requests() {
        let bytes = encode_request(&r).unwrap();
        assert_eq!(decode_request(&bytes).unwrap(), r, "{name}");
        for cut in 0..bytes.len() {
            assert!(decode_request(&bytes[..cut]).is_err(), "{name} cut {cut}");
        }
    }
    for (name, bytes, code) in bad_requests() {
        let error = decode_request(&bytes).unwrap_err();
        assert_eq!(error.code, code, "{name}");
        assert_eq!(error.context, Some((7, 1)), "{name}");
    }
    assert_eq!(ErrorCode::from_u16(50), Some(ErrorCode::MoveUnsupported));
    assert_eq!(ErrorCode::MoveUnsupported.name(), "RICH_MOVE_UNSUPPORTED");
    let error = Response::Error(ErrorCode::MoveUnsupported);
    let bytes = encode_reply(&Reply {
        doc_id: 7,
        request_id: 1,
        response: error.clone(),
    })
    .unwrap();
    assert_eq!(decode_reply(&bytes).unwrap().response, error);
}
